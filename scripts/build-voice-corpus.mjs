#!/usr/bin/env node
/**
 * A_75 §6.1 (P1) — build the `divergeFrom` corpus for the VoiceSpec generator.
 *
 * The `premise` engine works because its divergence instruction names REAL prior premises, not a
 * generic "be original". This does the same for voice: it measures what the recent manuscripts
 * actually sound like and emits a generated constant the prompt can cite by number.
 *
 * Measured rather than declared, because no VoiceSpec existed when these books were written — their
 * voice is whatever the pipeline happened to produce, and that is exactly what a new spec has to
 * diverge FROM.
 *
 *   node scripts/build-voice-corpus.mjs             # report only
 *   node scripts/build-voice-corpus.mjs --write     # regenerate the constant
 *
 * Re-run it after a batch of new runs. A stale corpus asks the generator to diverge from books that
 * are no longer the ones it is competing with.
 */

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = process.env.CML_WORKSPACE_ROOT || process.cwd();
const WRITE = process.argv.includes("--write");
const OUT = join(ROOT, "packages", "prompts-llm", "src", "constants", "voice-corpus.ts");
const WINDOW = 20;

const modulePath = join(ROOT, "packages", "prose-guard", "dist", "voice-spec.js");
if (!existsSync(modulePath)) {
  console.error(`\n  build @cml/prose-guard first — ${modulePath} is missing.\n`);
  process.exit(1);
}
const { measureVoice } = await import(pathToFileURL(modulePath).href);

// ── collect ──────────────────────────────────────────────────────────────────

const manuscripts = [];
const collectFrom = (dir) => {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (!statSync(full).isDirectory()) continue;
    if (name === "_archive") { collectFrom(full); continue; }
    const md = readdirSync(full).filter((f) => f.endsWith(".md") && !/readme|review|notes|debrief/i.test(f));
    if (!md.length) continue;
    const best = md.map((f) => ({ f, size: statSync(join(full, f)).size })).sort((a, b) => b.size - a.size)[0];
    if (best.size < 8000) continue;
    manuscripts.push({ story: name, path: join(full, best.f) });
  }
};
collectFrom(join(ROOT, "stories"));
manuscripts.sort((a, b) => a.story.localeCompare(b.story));

const recent = manuscripts.slice(-WINDOW).map((m) => {
  const text = readFileSync(m.path, "utf8");
  const title = (text.split(/\r?\n/).find((l) => l.trim().startsWith("#")) ?? "").replace(/^#+\s*/, "").trim();
  return { ...m, title, ...measureVoice(text) };
}).filter((m) => m.sentences >= 100);

if (recent.length < 3) {
  console.error(`\n  only ${recent.length} usable manuscript(s) — nothing to diverge from.\n`);
  process.exit(1);
}

// ── report ───────────────────────────────────────────────────────────────────

const means = recent.map((r) => r.mean);
const mean = means.reduce((a, b) => a + b, 0) / means.length;
const spread = Math.max(...means) - Math.min(...means);

console.log(`\n  A_75 P1 — voice corpus (last ${recent.length} manuscripts)\n`);
console.log(`   mean    sd   sentences  story`);
console.log(`  ${"-".repeat(72)}`);
for (const r of recent) {
  console.log(`  ${r.mean.toFixed(2).padStart(5)}  ${r.sd.toFixed(2).padStart(5)}  ${String(r.sentences).padStart(9)}  ${r.story}`);
}
console.log(`  ${"-".repeat(72)}`);
console.log(`  corpus mean ${mean.toFixed(2)} words/sentence, full spread ${spread.toFixed(2)} words\n`);

// The occupied bands, which is what the generator actually needs: where NOT to land.
const occupied = [...means].sort((a, b) => a - b);
console.log(`  occupied means: ${occupied.map((m) => m.toFixed(1)).join(", ")}\n`);

if (!WRITE) {
  console.log("  (nothing written — pass --write to regenerate the constant)\n");
  process.exit(0);
}

// ── emit ─────────────────────────────────────────────────────────────────────

const rows = recent
  .map((r) => `  { story: ${JSON.stringify(r.story)}, title: ${JSON.stringify(r.title)}, mean: ${r.mean.toFixed(2)}, sd: ${r.sd.toFixed(2)} },`)
  .join("\n");

const file = `/**
 * GENERATED by \`node scripts/build-voice-corpus.mjs --write\` — do not edit by hand.
 *
 * A_75 §6.1 (P1) — what the last ${recent.length} manuscripts actually sound like, so the VoiceSpec
 * generator can be told to diverge from real books rather than from a generic instruction to be
 * original. That specificity is why the \`premise\` engine works and nothing else does (A_72 §2.1).
 *
 * MEASURED at generation time: corpus mean ${mean.toFixed(2)} words per sentence, full spread
 * ${spread.toFixed(2)} words across ${recent.length} books. For scale, the WITHIN-book standard
 * deviation runs about 8 words — so the entire between-book spread of this corpus is a fraction of
 * the variation inside any single one of them. That is A_75 §3's finding as a number, and it is the
 * thing a new spec has to break.
 *
 * Re-run after a batch of new runs; a stale corpus asks the generator to diverge from books it is no
 * longer competing with.
 */

export interface VoiceCorpusEntry {
  story: string;
  title: string;
  /** Words per sentence, measured over the shipped manuscript. */
  mean: number;
  /** Within-book standard deviation of sentence length. */
  sd: number;
}

export const VOICE_CORPUS: ReadonlyArray<VoiceCorpusEntry> = [
${rows}
];

/** Arithmetic mean of the corpus means — the centre a new spec should NOT sit on. */
export const VOICE_CORPUS_MEAN = ${mean.toFixed(2)};
/** Widest gap between any two books in the corpus, in words per sentence. */
export const VOICE_CORPUS_SPREAD = ${spread.toFixed(2)};
export const VOICE_CORPUS_MANUSCRIPTS = ${recent.length};
`;

writeFileSync(OUT, file, "utf8");
console.log(`  wrote ${recent.length} entries to ${relative(ROOT, OUT)}\n`);
