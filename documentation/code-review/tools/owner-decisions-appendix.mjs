#!/usr/bin/env node
// Regenerate the appendix of documentation/code-review/OWNER-DECISIONS.md from LEDGER.md (itself generated from
// tools/ledger-state.tsv by build-ledger.mjs): every OPEN item that is an owner question (key *-Q*) or whose note
// names the owner, grouped by CR. Run after build-ledger.mjs:
//   node documentation/code-review/tools/owner-decisions-appendix.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LEDGER = join(ROOT, 'LEDGER.md');
const DOC = join(ROOT, 'OWNER-DECISIONS.md');
const MARKER = '<!-- GENERATED by documentation/code-review/tools/owner-decisions-appendix.mjs';
const CLOSED = new Set(['done', 'withdrawn', 'dup', 'decided']);

const rows = [];
for (const line of readFileSync(LEDGER, 'utf8').split(/\r?\n/)) {
  // | Key | P | Risk | CR | Status | Commit | Item | Note |
  const cells = line.split('|').slice(1, -1).map((c) => c.trim());
  if (cells.length !== 8 || cells[0] === 'Key' || /^-+$/.test(cells[0])) continue;
  const [key, , , cr, status, , item, note] = cells;
  if (!/^[A-Z0-9]+-[A-Z0-9]+$/.test(key) || CLOSED.has(status)) continue;
  if (!/-Q\d/.test(key) && !/owner/i.test(note)) continue;
  rows.push({ key, cr: cr || '(none)', status, item, note });
}
const crNum = (cr) => Number((cr.match(/\d+/) ?? ['999'])[0]);
const byCr = new Map();
for (const r of rows.sort((a, b) => crNum(a.cr) - crNum(b.cr) || a.key.localeCompare(b.key))) {
  if (!byCr.has(r.cr)) byCr.set(r.cr, []);
  byCr.get(r.cr).push(r);
}
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');
const out = [`${MARKER} from tools/ledger-state.tsv; do not edit by hand -->`, '', `**${rows.length} open items.**`, ''];
for (const [cr, list] of byCr) {
  out.push(`### ${cr} (${list.length})`, '', '| Item | What it asks | Ledger note |', '|---|---|---|');
  for (const r of list) out.push(`| ${r.key} | ${cell(r.item)} | ${cell(r.note)} |`);
  out.push('');
}
const doc = readFileSync(DOC, 'utf8');
const at = doc.indexOf(MARKER);
if (at < 0) throw new Error('marker missing from OWNER-DECISIONS.md');
writeFileSync(DOC, doc.slice(0, at) + out.join('\n'));
console.log(`owner-decisions appendix: ${rows.length} items in ${byCr.size} CRs`);
