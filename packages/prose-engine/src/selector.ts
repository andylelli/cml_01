/**
 * PROSE ENGINE v2 — THE SELECTOR (ANALYSIS_99 §10.6).
 *
 * ── WHY SELECTION IS THE MOVE THAT ATTACKS CONSISTENCY ───────────────────────────────────────────
 *
 * The owner's bar is 90 CONSISTENTLY, and a floor is a property of the WORST draft, not the mean.
 * Over August and September the headline ran mean 81.2, sd 3.6, floor 74 — and every book was the
 * model's first answer. WP-001 §8: post-training collapses an aligned model toward a few
 * stereotypical completions, and the one stage in this pipeline that generates several candidates
 * and picks (premise, five divergent candidates) is the one category with thirteen 9s. Verbalized
 * sampling recovers 1.6-2.1x diversity at inference time with no retraining.
 *
 * Drafting k times and keeping one cuts the lower tail without touching the mean. That is the whole
 * claim, and it is worth what it costs only if the thing doing the keeping agrees with the reader.
 *
 * ── SO THE SELECTOR WAS MEASURED BEFORE IT WAS BUILT ─────────────────────────────────────────────
 *
 * `scripts/selector-calibrate.mjs`, over all 49 manuscripts on disk with an external read and at
 * least 8,000 words (CLAUDE.md's floor: eight truncated May/June books manufacture relationships
 * with anything length-related):
 *
 *   instrument              rho vs the reader's headline
 *   register rate                 -0.502      the only previously validated predictor
 *   dialogue-open share           +0.337
 *   long-sentence share           +0.293
 *   wit per 10k                   +0.250
 *   em-dash per 1k                +0.222
 *   repetition per 10k            -0.152
 *
 *   register alone                 0.502
 *   THE COMPOSITE                  0.571
 *
 * **The composite beats the best single instrument by 0.07, and clears the bar the design wrote down
 * (|rho| >= 0.55).**
 *
 * ── AND THE FIRST RUN OF THIS SCRIPT DID NOT, FOR A REASON WORTH KEEPING ─────────────────────────
 *
 * It reported register at -0.454 and the composite at 0.524, and the bar was recorded as missed. The
 * cause was not the instruments: `story_20260912-1815/chatgpt-review.txt` holds THREE reads of TWO
 * books — 79 and 82 of a ballet-intermission book filed there by mistake, then 87, an as-written read
 * of the Lockwood book the folder actually holds — and both this script and
 * `external-read-ledger.mjs` took the FIRST, pairing the Lockwood manuscript with another book's
 * score. (The first version of this comment said "three reads of one book, 87 after repairs"; A_101
 * §10 corrected it.) Fixed at the ledger (W1) and imported here rather than re-implemented.
 *
 * AND A_101 §4, 2026-09-23: refitted on 55 v1 reads, register predicts v2's books at 88-90 and they
 * read 80-84. v2's register (0.012-0.034) is below every v1 book's (min 0.058), so these weights are
 * being used outside the range they were fitted on.
 *
 * ── AND THE WEIGHTS ARE THE ONES WRITTEN DOWN FIRST ──────────────────────────────────────────────
 *
 * The calibration script prints five candidate weightings: register only (0.502), register plus the
 * two page instruments (0.556), equal weight by sign (0.583), weight-by-measured-rho (0.574), and
 * the proposed weighting (0.571). They span 0.027, which says the signal is in USING SEVERAL
 * INSTRUMENTS and not in the tuning — so the shipped weighting is the one this file proposed before
 * the table existed. Picking the top row after seeing it would be fitting on the data that judges it,
 * with n=49 and six parameters.
 *
 * ── HARD GATES ARE NOT INSTRUMENTS ───────────────────────────────────────────────────────────────
 *
 * Contract fidelity — a clue missing, the culprit named early, a clue id in the prose — is not a
 * quality score to be traded against register. A draft with hard failures ranks below every draft
 * without, and is NEVER discarded: L4, the run always has a book. If every draft fails, the one with
 * the fewest proceeds and each failure becomes a finding for the editor.
 */

